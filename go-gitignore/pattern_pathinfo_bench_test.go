// kubernetesNested are three of the nested .gitignore files kubernetes carries.
// In a real walk these stack on top of the root one, so a file below them is
// tested against both lists.
const kubernetesNested = `
# hack/tools/.gitignore
/bin/

# test/images/agnhost/.gitignore
agnhost

# cluster/gce/gci/mounter/.gitignore
mounter
`

func BenchmarkRelativePatternLoop(b *testing.B) {
	_cases := []struct {
		Name     string
		Patterns string
		Path     string
		IsDir    bool
	}{
		// the theory's stated case: fifty name patterns, all missing
		{"fifty_names_shallow_miss", fiftyNames, "main.go", false},
		{"fifty_names_deep_miss", fiftyNames, "staging/src/k8s.io/apiserver/pkg/server/options/etcd.go", false},
		{"fifty_names_hit", fiftyNames + "main.go\n", "pkg/a/b/main.go", false},

		// realistic corpora
		{"k8s_root_miss", kubernetesGitignore, "staging/src/k8s.io/apiserver/pkg/server/options/etcd.go", false},
		{"k8s_root_hit", kubernetesGitignore, "pkg/a/b/foo.pyc", false},
		{"k8s_root_dir", kubernetesGitignore, "staging/src/k8s.io/apiserver/pkg/server", true},
		{"k8s_stacked_miss", kubernetesGitignore + kubernetesNested, "staging/src/k8s.io/apiserver/pkg/server/options/etcd.go", false},
		{"linux_root_miss", linuxGitignore, "drivers/net/ethernet/intel/e1000e/netdev.c", false},
		{"linux_root_hit", linuxGitignore, "drivers/net/ethernet/intel/e1000e/netdev.o", false},
		{"linux_root_dir", linuxGitignore, "drivers/net/ethernet/intel/e1000e", true},
	}

	for _, _case := range _cases {
		_ignore := gitignore.New(strings.NewReader(_case.Patterns), "/base", nil)
		b.Run(_case.Name, func(b *testing.B) {
			b.ReportAllocs()
			for _i := 0; _i < b.N; _i++ {
				_ignore.Relative(_case.Path, _case.IsDir)
			}
		})
	}
}
