// Benchmarks for the pattern loop in Relative, which derives the base name of
// the path once for the whole pattern list rather than once per pattern.
//
// The base name only matters to name patterns, so what these measure is how
// much of a real ignore file is name patterns and how long the paths are: a
// deep path and a list of names that all miss is the shape the derivation was
// repeated most often for.

// fiftyNames is the stated shape of the theory: an ignore file of fifty name
// patterns, none of which match, so every one of them reaches the point of
// wanting the base name.
var fiftyNames = func() string {
	var _b strings.Builder
	for _i := 0; _i < 25; _i++ {
		fmt.Fprintf(&_b, "nomatch%02d\n", _i)
		fmt.Fprintf(&_b, "*.nomatch%02d\n", _i)
	}
	return _b.String()
}()

